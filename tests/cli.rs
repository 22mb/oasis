//! Runs the `oasis-gen` binary: argument parsing, stdin input and file output.

use std::io::Write;
use std::process::{Command, Output, Stdio};

const PETSTORE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/petstore.yaml");
const GOLDEN: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/golden/petstore.ts");

fn run(args: &[&str], stdin: &str) -> Output {
    let mut child = Command::new(env!("CARGO_BIN_EXE_oasis-gen"))
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    child
        .stdin
        .take()
        .unwrap()
        .write_all(stdin.as_bytes())
        .unwrap();
    child.wait_with_output().unwrap()
}

fn text(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes).into_owned()
}

#[test]
fn writes_the_client_to_stdout() {
    let out = run(&[PETSTORE], "");
    assert!(out.status.success(), "{}", text(&out.stderr));
    assert!(out.stderr.is_empty());
    assert_eq!(text(&out.stdout), std::fs::read_to_string(GOLDEN).unwrap());

    let out = run(&["--lang", "ts", PETSTORE], "");
    assert!(out.status.success(), "{}", text(&out.stderr));
}

#[test]
fn reads_json_from_stdin() {
    let doc = r#"{
        "openapi": "3.2.0",
        "info": {"title": "Stdin", "version": "2"},
        "paths": {"/a": {"get": {"responses": {"204": {"description": "ok"}}}}}
    }"#;
    let out = run(&["-"], doc);
    assert!(out.status.success(), "{}", text(&out.stderr));
    let code = text(&out.stdout);
    assert!(
        code.starts_with("// Generated by oasis-gen from \"Stdin 2\"."),
        "{code}"
    );
    assert!(code.contains("\"/a\": {\n    GET: {"), "{code}");
}

#[test]
fn writes_to_the_output_file() {
    let dir = std::env::temp_dir().join(format!("oasis-gen-cli-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("api.ts");
    let out = run(&["-o", file.to_str().unwrap(), PETSTORE], "");
    assert!(out.status.success(), "{}", text(&out.stderr));
    assert!(out.stdout.is_empty());
    assert_eq!(
        std::fs::read_to_string(&file).unwrap(),
        std::fs::read_to_string(GOLDEN).unwrap()
    );
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn prints_version_and_help() {
    let out = run(&["-V"], "");
    assert!(out.status.success());
    assert_eq!(
        text(&out.stdout).trim_end(),
        format!("oasis-gen {}", env!("CARGO_PKG_VERSION"))
    );

    let out = run(&["--help"], "");
    assert!(out.status.success());
    assert!(text(&out.stdout).contains("Usage: oasis-gen <SPEC>"));
}

#[test]
fn rejects_bad_invocations() {
    let cases: [(&[&str], &str); 6] = [
        (&[], "missing <SPEC>"),
        (&["--nope", PETSTORE], "unknown option `--nope`"),
        (&[PETSTORE, "extra"], "unexpected argument `extra`"),
        (&[PETSTORE, "-o"], "missing value for --output"),
        (
            &["--lang", "kotlin", PETSTORE],
            "unsupported language `kotlin`",
        ),
        (
            &["/nonexistent/openapi.yaml"],
            "cannot read /nonexistent/openapi.yaml",
        ),
    ];
    for (args, needle) in cases {
        let out = run(args, "");
        assert_eq!(out.status.code(), Some(1), "{args:?}");
        assert!(out.stdout.is_empty(), "{args:?}");
        let stderr = text(&out.stderr);
        assert!(
            stderr.starts_with("error: ") && stderr.contains(needle),
            "{args:?}: {stderr}"
        );
    }
}

#[test]
fn reports_document_errors() {
    let out = run(&["-"], "openapi: 4.0.0\n");
    assert_eq!(out.status.code(), Some(1));
    assert!(out.stdout.is_empty());
    let stderr = text(&out.stderr);
    assert!(
        stderr.contains("supports 3.0.x, 3.1.x and 3.2.x"),
        "{stderr}"
    );

    let out = run(&["-"], "{\"openapi\": ");
    assert_eq!(out.status.code(), Some(1));
    let stderr = text(&out.stderr);
    assert!(stderr.contains("invalid JSON"), "{stderr}");
}
